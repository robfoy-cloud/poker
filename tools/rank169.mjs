// Builds public/js/handranks.js: the 169 starting hands ordered by equity
// against two random hands (a reasonable proxy for a full-ring table).
import { evaluate, newDeck, RANK_CHAR } from '../public/js/cards.js';
import { writeFileSync } from 'fs';
const ITERS = +process.argv[2] || 6000;
const codes = [];
for (let a = 14; a >= 2; a--) for (let b = a; b >= 2; b--) {
  if (a === b) codes.push({ code: RANK_CHAR[a] + RANK_CHAR[b], a, b, suited: false, combos: 6 });
  else { codes.push({ code: RANK_CHAR[a] + RANK_CHAR[b] + 's', a, b, suited: true, combos: 4 }); codes.push({ code: RANK_CHAR[a] + RANK_CHAR[b] + 'o', a, b, suited: false, combos: 12 }); }
}
for (const c of codes) c.code = c.code.replace(/10/g, 'T');
for (const h of codes) {
  const hole = [{ r: h.a, s: 's' }, { r: h.b, s: h.suited ? 's' : 'h' }];
  const k = c => c.r + c.s;
  const known = new Set(hole.map(k));
  const rest = newDeck().filter(c => !known.has(k(c)));
  let w = 0;
  for (let i = 0; i < ITERS; i++) {
    for (let j = 0; j < 9; j++) { const r = j + Math.floor(Math.random() * (rest.length - j)); [rest[j], rest[r]] = [rest[r], rest[j]]; }
    const board = rest.slice(4, 9);
    const me = evaluate([...hole, ...board]).score;
    const o1 = evaluate([rest[0], rest[1], ...board]).score, o2 = evaluate([rest[2], rest[3], ...board]).score;
    const best = Math.max(o1, o2);
    if (me > best) w += 1; else if (me === best) w += 1 / (1 + (o1 === me) + (o2 === me));
  }
  h.eq = w / ITERS;
}
codes.sort((x, y) => y.eq - x.eq);
let cum = 0;
const out = codes.map(c => { cum += c.combos; return [c.code, +(cum / 1326).toFixed(4), +c.eq.toFixed(3)]; });
writeFileSync(new URL('../public/js/handranks.js', import.meta.url),
  `// Generated by tools/rank169.mjs — starting hands, best first.\n// [hand, share of all hands at least this good (0-1), equity vs two random hands]\nexport const HAND_RANKS = ${JSON.stringify(out)};\n`);
